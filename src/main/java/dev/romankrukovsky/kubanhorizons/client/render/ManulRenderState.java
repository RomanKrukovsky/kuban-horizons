package dev.romankrukovsky.kubanhorizons.client.render;

import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;

/**
 * Состояние рендера манула.
 *
 * <p>В 26.2 модель не читает сущность напрямую: {@code createRenderState()}
 * вызывается заново на каждом кадре, поэтому здесь лежит только снимок, а не
 * накопленная память. Всё, что должно «помнить» фазу движения, считается в
 * модели от {@link #ageInTicks} и {@link #seed} — так анимация не зависит от
 * времени жизни объекта состояния.</p>
 *
 * <p>Именно поэтому здесь нет {@code AnimationState}, как у ванильной жабы:
 * ванильные мобы держат таймеры на самой сущности, а класс {@code Manul}
 * принадлежит другому агенту и синхронизирует только булевы флаги. Городить
 * зеркало таймеров на клиенте было бы лишней связностью — от флагов и общего
 * тика получается то же самое без правок в сущности.</p>
 */
public class ManulRenderState extends LivingEntityRenderState {
    /** Суффикс текстуры: {@code manul_<coat>.png}. */
    public String coat = "steppe";

    /** Шипит: уши прижаты, зверь предупреждает. */
    public boolean hissing;
    /** Замер и разглядывает происходящее — «взгляд манула на хаос». */
    public boolean frozen;
    /** Сидит «булкой»: максимально круглый силуэт. */
    public boolean sitting;
    /** Спит, свернувшись клубком. */
    public boolean sleeping;
    /** В воздухе: прыжок через плетень или балку. */
    public boolean airborne;
    /** Под открытым дождём: шерсть прижата, зверь ищет укрытие. */
    public boolean inRain;

    /**
     * Пушистость 0..1 — сезонная шуба.
     *
     * <p>Зимой манул визуально круглее, летом суше. Сделано масштабом уже
     * существующих частей, а не второй моделью и не новыми кубами: по
     * ART_BIBLE §4 важен силуэт, а «шар зимой / кот летом» — это именно
     * силуэт.</p>
     */
    public float fluff = 0.5F;

    /**
     * Постоянный сдвиг фазы, свой у каждой особи.
     *
     * <p>Без него два манула в кадре дышали бы и умывались синхронно, что сразу
     * читается как «клоны». Берётся из id сущности — стабильно между кадрами и
     * не требует хранить состояние.</p>
     */
    public float seed;
}
