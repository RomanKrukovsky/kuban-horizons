package dev.romankrukovsky.kubanhorizons.client;

import dev.romankrukovsky.kubanhorizons.config.KHClientConfig;
import net.minecraft.util.RandomSource;

/**
 * Плотность декоративных частиц мода.
 *
 * <p>Настройка {@code particles.density} обещала «множитель плотности
 * декоративных частиц», но её не читал никто: значение можно было выставить
 * в ноль, и листва всё равно сыпалась с прежней частотой. Здесь настройка
 * получает единственную точку применения, через которую проходят все
 * декоративные частицы мода.</p>
 *
 * <p>Зачем она нужна: частицы — первое, что убирают на слабой машине, и
 * первое, что мешает при съёмке. Ванильная опция «Particles» действует
 * глобально и грубо (all/decreased/minimal); эта — только на частицы мода
 * и плавно, включая полное отключение.</p>
 *
 * <p>Класс намеренно не {@code EventBusSubscriber}: он не слушает события,
 * а служит фильтром, который блоки спрашивают перед выпуском частицы.
 * Вызывается из {@code animateTick}, а его дёргает только
 * {@code ClientLevel} — на выделенном сервере этот путь не исполняется.</p>
 *
 * <p>Тем не менее чтение конфига обёрнуто в защиту от незагруженного
 * состояния. Класс лежит в общем (не {@code Dist.CLIENT}) исходнике,
 * потому что его вызывают блоки, а клиентский конфиг регистрируется только
 * в клиентской входной точке: обращение к значению до загрузки файла
 * бросает исключение. Падение мира из-за ползунка частиц было бы худшим
 * исходом, чем частица, показанная лишний раз.</p>
 */
public final class KHParticles {
    private KHParticles() {
    }

    /**
     * Выпускать ли очередную декоративную частицу.
     *
     * <p>Множитель больше единицы не «дорисовывает» частицы, которых нет:
     * решение принимается по каждой частице, которую движок уже собрался
     * выпустить, поэтому 2.0 означает «не реже обычного», а не удвоение.
     * Загущать поток пришлось бы отдельным циклом в каждом блоке — цена
     * выше пользы, а описание настройки говорит именно о плотности,
     * которую игрок хочет прежде всего убавить.</p>
     *
     * @param random источник случайности вызывающего блока
     * @return {@code true}, если частицу следует показать
     */
    public static boolean allow(RandomSource random) {
        double density = density();
        if (density >= 1.0D) {
            return true;
        }
        // Ноль — жёсткий ноль: без этой ветки nextDouble() < 0.0 всё равно
        // ложно, но явная проверка избавляет от вызова генератора.
        return density > 0.0D && random.nextDouble() < density;
    }

    /**
     * Текущий множитель плотности, либо 1.0, если конфиг ещё не загружен.
     *
     * <p>Незагруженный конфиг — не ошибка, а нормальное состояние вне
     * клиента (выделенный сервер, датаген, GameTest). Значение по умолчанию
     * означает «ничего не фильтруем».</p>
     */
    public static double density() {
        try {
            return KHClientConfig.particleDensity();
        } catch (IllegalStateException notLoadedYet) {
            return 1.0D;
        }
    }
}
