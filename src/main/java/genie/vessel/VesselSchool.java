package genie.vessel;

/**
 * Schools of magic that vessels can specialize in.
 * Determines the type of wishes and effects a vessel can handle.
 */
public enum VesselSchool {
    /**
     * Fire magic - grants wishes related to heat, fire, and energy.
     */
    PYRO,

    /**
     * Water magic - grants wishes related to liquids, ice, and purification.
     */
    HYDRO,

    /**
     * Earth magic - grants wishes related to terrain, plants, and minerals.
     */
    GEO,

    /**
     * Air magic - grants wishes related to movement, weather, and sound.
     */
    AERO,

    /**
     * Light magic - grants wishes related to illumination, healing, and protection.
     */
    LUMI
}
