class Cube:
    """Кубоид в координатах модели.

    ``pos`` — начало (минимальный угол), НЕ центр; ``size`` — габариты.
    ``uv`` проставляет упаковщик атласа, вручную его задавать нельзя.
    """

    __slots__ = ("name", "pos", "size", "inflate", "mirror", "uv", "glow")

    def __init__(self, name, pos, size, inflate=0.0, mirror=False, glow=False):
        self.name = name
        self.pos = [float(v) for v in pos]
        self.size = [float(v) for v in size]
        self.inflate = float(inflate)
        self.mirror = bool(mirror)
        self.glow = bool(glow)
        self.uv = None

    # Габариты с учётом inflate — именно они участвуют в проверке пересечений.
    def lo(self):
        return [self.pos[i] - self.inflate for i in range(3)]

    def hi(self):
        return [self.pos[i] + self.size[i] + self.inflate for i in range(3)]

    def footprint(self):
        """Размер box-UV развёртки: ширина 2D+2W, высота D+H.

        Габариты округляются вверх ПООСЕВО, а не по сумме: грани рисуются
        целыми пикселями, поэтому кубоид 4.6×4×3.8 занимает 2·4+2·5=18 px,
        а не ceil(2·3.8+2·4.6)=17. Считать по сумме — значит зарезервировать
        на пиксель меньше, чем реально закрашивается, и соседняя развёртка
        будет затёрта.
        """
        w = max(1, int(-(-self.size[0] // 1)))
        h = max(1, int(-(-self.size[1] // 1)))
        d = max(1, int(-(-self.size[2] // 1)))
        return (2 * d + 2 * w, d + h)


class Bone:
    __slots__ = ("name", "parent", "pivot", "rotation", "cubes")

    def __init__(self, name, parent, pivot, rotation=None):
        self.name = name
        self.parent = parent
        self.pivot = [float(v) for v in pivot]
        self.rotation = [float(v) for v in rotation] if rotation else None
        self.cubes = []

    def add(self, *args, **kw):
        c = Cube(*args, **kw)
        self.cubes.append(c)
        return c


def build():
    """Возвращает список костей джиннии в порядке экспорта."""
    bones = []

    def bone(name, parent, pivot, rotation=None):
        b = Bone(name, parent, pivot, rotation)
        bones.append(b)
        return b

    # --- Скелет ---------------------------------------------------------------
    bone("root", None, [0, 0, 0])
    body = bone("body", "root", [0, Y_WAIST, 0])
    torso = bone("torso", "body", [0, Y_HEAD_BOT, 0])
    head = bone("head", "torso", [0, Y_HEAD_BOT, 0])
    hair_mass = bone("hair_mass", "torso", [0, 31, 2])
    hair_tips = bone("hair_tips", "hair_mass", [0, 13, 2])
    earring_l = bone("earring_l", "head", [4.5, 33, -1])
    earring_r = bone("earring_r", "head", [-4.5, 33, -1])
    arm_l = bone("arm_l", "torso", [5.5, 29, 0])
    arm_r = bone("arm_r", "torso", [-5.5, 29, 0])
    hips = bone("hips", "body", [0, Y_WAIST, 0])
    belt = bone("belt", "hips", [0, Y_BELT, 0])
    pendant_l = bone("pendant_l", "belt", [3.5, 13.5, Z_PENDANT])
    pendant_c = bone("pendant_c", "belt", [0, 13.5, Z_PENDANT - 0.2])
    pendant_r = bone("pendant_r", "belt", [-3.5, 13.5, Z_PENDANT])
    rushnyk = bone("rushnyk", "belt", [X_RUSHNYK + 1.5, 14.0, Z_RUSHNYK])
    rushnyk_mid = bone("rushnyk_mid", "rushnyk", [X_RUSHNYK + 1.5, 3.0, Z_RUSHNYK])
    rushnyk_tip = bone("rushnyk_tip", "rushnyk_mid",
                       [X_RUSHNYK + 1.5, -4.0, Z_RUSHNYK])

    # --- Голова --------------------------------------------------------------
    # Кубическая голова Minecraft: 8×8×8, лицо смотрит в -Z.
    head.add("head", [-4, 30, -4], [8, 8, 8])
    # Волосы на голове разбиты так, чтобы НИ ОДИН кубоид не оказался перед
    # лицом. Полагаться на прозрачные пиксели шапки нельзя: любая правка
    # текстуры или mipmap мгновенно закрывает глаза волосами.
    # Верхняя шапка живёт выше линии глаз (Y_FACE_TOP) и уходит назад.
    head.add("hair_top", [-4.5, Y_FACE_TOP, -4.5], [9, 3.5, 9.5])
    # Пряди по бокам лица: стоят СНАРУЖИ головы по X, лицо не перекрывают.
    # Размеры целые: дробные габариты дают box-UV footprint с округлением
    # вверх, и часть развёртки остаётся незакрашенной полосой.
    head.add("hair_side_l", [4.0, 30, -4.0], [1, 6, 8])
    head.add("hair_side_r", [-5.0, 30, -4.0], [1, 6, 8])
    # Затылок ниже шапки.
    head.add("hair_nape", [-4.5, 30, 2.5], [9, 6, 2])
    # Чёлка — тонкая полоса ровно по линии волос, не ниже.
    head.add("hair_fringe", [-4.5, Y_FACE_TOP, -5.0], [9, 3, 1])
    # Очки: тонкая прямоугольная оправа, вынесена перед лицом и перед чёлкой.
    head.add("glasses", [-4, 33, -5.0], [8, 3, 1])
    # Диадема с крупным центральным сапфиром.
    head.add("tiara", [-4.5, 36.5, -5.2], [9, 2, 1], glow=True)
    head.add("tiara_gem_c", [-1, 37.5, -5.7], [2, 2, 1], glow=True)
    head.add("tiara_gem_l", [2.5, 37.0, -5.7], [1, 1, 1], glow=True)
    head.add("tiara_gem_r", [-3.5, 37.0, -5.7], [1, 1, 1], glow=True)
    earring_l.add("earring_l", [4.2, 30, -1.5], [1, 3, 1], glow=True)
    earring_r.add("earring_r", [-5.2, 30, -1.5], [1, 3, 1], glow=True)

    # --- Волосы (задняя масса) ----------------------------------------------
    # Родитель — torso: см. пояснение в докстринге модуля.
    # Масса начинается за спиной (Z_HAIR) и уходит назад, поэтому по глубине
    # она не конкурирует ни с тазом, ни с поясом, ни с хвостом.
    hair_mass.add("hair_mass", [-5, 14, Z_HAIR], [10, 18, 6])
    # Боковые локоны свисают вдоль лопаток, но остаются позади плеч и рук:
    # X внутри полуширины груди, Z — за линией торса.
    hair_mass.add("hair_lock_l", [3.4, 20, 1.4], [2, 12, 2])
    hair_mass.add("hair_lock_r", [-5.4, 20, 1.4], [2, 12, 2])
    hair_tips.add("hair_tips", [-4, Y_TAIL_TOP - 4.0, Z_HAIR + 0.4], [8, 9, 5])

    # --- Торс: песочные часы -------------------------------------------------
    # Три яруса вместо одного кубоида: грудь W_BUST, талия W_WAIST, между ними
    # переход. Вогнутая дуга читается именно на стыках ярусов.
    z0 = -D_CHEST / 2
    torso.add("chest", [-W_BUST / 2, Y_BUST - 2.0, z0], [W_BUST, 6.0, D_CHEST])
    torso.add("ribs", [-4.0, Y_WAIST + 2.0, z0 + 0.4], [8.0, 4.0, D_CHEST - 0.8])
    torso.add("waist", [-W_WAIST / 2, Y_WAIST - 1.0, z0 + 0.7],
              [W_WAIST, 3.0, D_CHEST - 1.4])
    # Лиф надет на грудь: inflate 0.5, поэтому сам кубоид на 1 px уже и ниже.
    torso.add("bodice", [-(W_BUST - 1) / 2, Y_BUST - 1.5, z0 + 0.5],
              [W_BUST - 1, 5.0, D_CHEST - 1.0], inflate=0.5)
    # Коралловые бусы: три короткие нити, поэтому кубоид высотой 3 px.
    torso.add("necklace", [-3, 28, z0 - 0.1], [6, 3, 1])
    # Украшение пупка — сапфир на короткой золотой цепочке (в основном текстура).
    torso.add("navel_gem", [-1, Y_WAIST - 0.5, z0 + 0.2], [2, 2, 1])

    # --- Руки ----------------------------------------------------------------
    # Кисть — сплошной кубоид: прорезь на 4 px читается как дырка.
    # Рукав и браслеты имеют inflate 0.5, поэтому зазор считается от их
    # раздутой границы, а не от самого кубоида руки.
    inner = W_BUST / 2 + ARM_GAP + 0.5   # внутренняя грань раздутых деталей
    for arm, sx in ((arm_l, 1), (arm_r, -1)):
        x_arm = inner + 0.5 if sx > 0 else -(inner + 0.5 + 4)
        x_wide = inner if sx > 0 else -(inner + 5)
        mir = sx < 0
        arm.add("arm", [x_arm, 17.0, -2.0], [4, 12, 4], mirror=mir)
        arm.add("sleeve", [x_wide, 24.0, -2.5], [5, 4, 5],
                inflate=0.5, mirror=mir)
        arm.add("bangles", [x_wide, 18.5, -2.5], [5, 3, 5],
                inflate=0.5, mirror=mir)
    # Подсолнух — осознанная асимметрия, только на одном плече.
    arm_r.add("sunflower", [-(inner + 5.5), 26.5, -1.5], [3, 3, 2])

    # --- Таз -----------------------------------------------------------------
    hips.add("hips", [-W_HIP / 2, Y_HIP - 1.0, -D_HIPS / 2], [W_HIP, 6.0, D_HIPS])
    hips.add("hips_low", [-4.6, Y_TAIL_TOP - 0.5, -D_HIPS / 2 + 0.3],
             [9.2, 3.0, D_HIPS - 0.6])

    # --- Пояс ----------------------------------------------------------------
    # Пояс шире таза и глубже его: он обязан визуально накрыть и стык бёдер,
    # и основание хвоста, иначе на этом шве видно смену цвета.
    belt.add("belt", [-5.8, Y_BELT - 1.5, -D_BELT / 2], [11.6, 4.0, D_BELT])
    belt.add("belt_gem_c", [-1, Y_BELT - 0.5, -D_BELT / 2 - 0.4], [2, 2, 1])
    belt.add("belt_gem_l", [3.0, Y_BELT - 0.5, -D_BELT / 2 - 0.3], [2, 2, 1])
    belt.add("belt_gem_r", [-5.0, Y_BELT - 0.5, -D_BELT / 2 - 0.3], [2, 2, 1])
    # Подвески висят ПЕРЕД тазом (Z_PENDANT), только спереди и по бокам; со
    # спины их нет даже в текстуре. Низ подвесок упирается в Y_TAIL_TOP:
    # если опустить их ниже, они воткнутся в основание хвоста.
    pendant_l.add("pendant_l", [3.0, Y_TAIL_TOP, Z_PENDANT], [1, 3, 1])
    pendant_c.add("pendant_c", [-0.5, Y_TAIL_TOP, Z_PENDANT - 0.2], [1, 3.5, 1])
    pendant_r.add("pendant_r", [-4.0, Y_TAIL_TOP, Z_PENDANT], [1, 3, 1])

    # --- Рушник: длинная вышитая полоса сбоку -------------------------------
    # Три звена вместо двух: полоса должна быть в 2–3 раза длиннее прежней
    # и качаться с затуханием, а не болтаться как одна доска. Вынесена за
    # X_RUSHNYK и Z_RUSHNYK, чтобы обрамлять бок, но не лезть на хвост.
    rushnyk.add("rushnyk", [X_RUSHNYK, 3.0, Z_RUSHNYK], [3, 11, 1])
    rushnyk_mid.add("rushnyk_mid", [X_RUSHNYK, -4.0, Z_RUSHNYK], [3, 7, 1])
    rushnyk_tip.add("rushnyk_tip", [X_RUSHNYK, -9.0, Z_RUSHNYK], [3, 5, 1])

    # --- Хвост ---------------------------------------------------------------
    # Семь сегментов, каждый вложен в предыдущий. Все центрированы по X/Z:
    # S-образность даёт только rotation. Смена знака между tail3 и tail4 —
    # перегиб, нарастание к концу — крючок.
    # Ширина и глубина монотонно убывают: любой «раздутый» сегмент в середине
    # читается как опухоль, а не как дым.
    tail_w = [W_TAIL_TOP, 7.4, 6.8, 6.2, 5.4, 4.6, 3.6]
    tail_d = [6.4, 6.0, 5.6, 5.0, 4.4, 3.8, 3.0]
    tail_h = [5.0, 5.0, 4.5, 4.5, 4.0, 4.0, 4.0]
    # Углы задаются АБСОЛЮТНЫМИ (в мировой вертикали), а в geo пишутся
    # разностью с родителем: повороты вложенных костей складываются, и если
    # писать в geo сразу «наклон сегмента», хвост уедет в сторону на
    # накопленный угол. Absolute-набор подобран так, чтобы кривая перешла
    # через ноль у tail4 и вернулась к центральной оси у кончика.
    #
    # Две плоскости, а не одна: S по Z (вид спереди) и S по X (вид сбоку).
    # Без второго набора хвост читается S-образным только с одной точки
    # обзора, а сбоку выглядит прямой палкой.
    tail_abs_z = [10, 20, 14, 0, -16, -34, -58]   # поворот вокруг Z
    tail_abs_x = [6, 14, 10, -2, -14, -24, -34]   # поворот вокруг X
    tail_rot_z = [tail_abs_z[0]] + [tail_abs_z[i] - tail_abs_z[i - 1]
                                    for i in range(1, 7)]
    tail_rot_x = [tail_abs_x[0]] + [tail_abs_x[i] - tail_abs_x[i - 1]
                                    for i in range(1, 7)]

    parent = "hips"
    y = Y_TAIL_TOP
    for i in range(7):
        w, d, h = tail_w[i], tail_d[i], tail_h[i]
        b = bone("tail%d" % (i + 1), parent, [0, y, 0],
                 [tail_rot_x[i], 0, tail_rot_z[i]])
        # Заход на 1 px в родителя: иначе поворот открывает щель на стыке.
        b.add("tail%d" % (i + 1), [-w / 2, y - h, -d / 2], [w, h, d])
        bones.append(bones.pop(bones.index(b)))
        parent = b.name
        y -= (h - 1.0)

    return bones


def bones_by_name(bones):
    return {b.name: b for b in bones}
