"""Кубанская джинния: единый источник правды для геометрии и текстуры.

Здесь нет ни PIL, ни JSON — только описание персонажа в пикселях Minecraft
(1 блок = 16 px). Геометрию собирает ``gen_genie_model``, текстуру —
``gen_genie_texture``; оба читают этот модуль, поэтому UV кубоида и рисунок
на нём физически не могут разъехаться.

Оси: X вправо (экранное «вправо» = сторона левой руки игрока-наблюдателя),
Y вверх, Z вперёд (к наблюдателю Z отрицательный, как во всех моделях
Minecraft). Y=0 — уровень парения; хвост уходит в минус.

Ключевые решения, которые нельзя менять по невнимательности:

* ``hair_mass`` висит на ``torso``, а не на ``head``. Иначе поворот головы за
  игроком протащит восьмипиксельную заднюю массу волос сквозь спину.
* Силуэт «песочные часы» задаётся ТОЛЬКО шириной кубоидов торса, а не
  масштабом костей: анимации крутят кости, и любой scale на них поехал бы.
* Руки отодвинуты от торса на ``ARM_GAP``. Пересечение руки с грудью или
  лифом даёт z-fighting на каждом кадре покачивания.
* Сегменты хвоста центрированы по X и Z. Изгиб — исключительно ``rotation``
  костей, иначе анимация волны рвёт хвост на части.
"""

