def _shade(c, k):
    """Затемняет (k<1) или осветляет (k>1) цвет, сохраняя альфу."""
    r, g, b, a = c
    f = lambda v: max(0, min(255, int(round(v * k))))
    return (f(r), f(g), f(b), a)


