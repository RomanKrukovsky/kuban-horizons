"""Текстуры кубанского манула (Otocolobus manul) — талисмана мода, 64×64.

Четыре природных варианта окраса, одна развёртка, разные палитры:

    manul_steppe.png    степной серый — базовый
    manul_sand.png      светло-песочный (выгоревшая степь)
    manul_mountain.png  тёмный горный
    manul_silver.png     серебристый — редкий

Развёртка совпадает с ManulModel и построена на ванильной
QuadrupedModel.createBodyMesh — той же, что у кабана и овчарки
(см. KubanQuadrupedModel): голова 0,0; корпус 28,8; лапа 0,16.
Свои части лежат ниже y=32, где ванильная зона уже не мешает:

    head   (0,0)   8x8x8      body  (28,8)  10x16x8
    leg    (0,16)  4x6x4      r_ear (0,32)  3x2x1
    l_ear  (8,32)  3x2x1      ruff  (16,32) 10x4x2
    tail   (42,32) 3x10x3

Слоты посчитаны по раскладке граней (top/bottom/right/front/left/back) и
проверены на пересечения: коллизий нет, занято 38.2% атласа. Промах в
texOffs здесь означает шерсть корпуса на морде — тот же класс ошибки, о
котором предупреждает комментарий в KubanQuadrupedModel.

Про манула важно, что он читается тремя признаками, а не общей мохнатостью:
широкая плоская морда с опушкой, тёмные кольца на хвосте и вечно недовольное
выражение. Поэтому брови — это отдельная тёмная полоса над глазами (2 px),
а кольца хвоста — 2 px через 2 px: тонкие полосы на дистанции сливаются в
серое пятно, и зверь теряет узнаваемость. Этот урок стоил моду одной
переделки пчелы, у которой полосы были технически на месте, но не читались.

Палитра по ART_BIBLE §2: тёплые степные серо-песочные тона родственны
выгоревшей траве (#b7a95c) и саману (#b09468), поэтому манул стоит в одном
мире с кабаном и овчаркой. Глаза — янтарные, единственный насыщенный акцент.
Чистый чёрный и белый не используются (§8).
"""
import os

from PIL import Image

from texlib import hline, px, rect

OUT = os.path.join(os.path.dirname(__file__), "..", "..",
                   "src/main/resources/assets/kubanhorizons/textures/entity")

# --- Раскладка (должна совпадать с ManulModel) ---
UV_HEAD = (0, 0, 8, 8, 8)
UV_BODY = (28, 8, 10, 16, 8)
UV_LEG = (0, 16, 4, 6, 4)
UV_EAR_R = (0, 32, 3, 2, 1)
UV_EAR_L = (8, 32, 3, 2, 1)
UV_RUFF = (16, 32, 10, 4, 2)
UV_TAIL = (42, 32, 3, 10, 3)

# Янтарь общий для всех вариантов: цвет глаз у манула не зависит от окраса,
# и он же — единственное насыщенное пятно на звере.
AMBER = (226, 162, 44, 255)
AMBER_HI = (244, 196, 92, 255)
PUPIL = (38, 28, 18, 255)          # тёмно-бурый, не чёрный (ART_BIBLE §8)
GLINT = (248, 238, 214, 255)


class Coat:
    """Палитра одного окраса.

    Восемь структурных тонов: этого хватает на объём и рисунок и оставляет
    запас под точечные акценты (глаз, блик, нос) в пределах §2.
    """

    def __init__(self, name, deep, dark, base, hi, pale, face, ruff, nose):
        self.name = name
        self.deep = deep      # кольца, обводка, брови — самый тёмный
        self.dark = dark      # теневые грани
        self.base = base      # основной тон шкуры
        self.hi = hi          # освещённый верх (свет сверху-слева)
        self.pale = pale      # брюхо, опушка морды
        self.face = face      # плоскость лица — светлее шкуры
        self.ruff = ruff      # щёчная опушка
        self.nose = nose


# Степной серый — базовый. Тёплый серо-песочный, родня выгоревшей траве.
STEPPE = Coat(
    "manul_steppe",
    deep=(52, 44, 34, 255), dark=(88, 80, 64, 255), base=(126, 118, 100, 255),
    hi=(158, 148, 126, 255), pale=(198, 188, 164, 255),
    face=(178, 168, 146, 255), ruff=(208, 198, 176, 255),
    nose=(140, 104, 96, 255),
)

# Светло-песочный: манул выгоревшей августовской степи.
SAND = Coat(
    "manul_sand",
    deep=(84, 66, 44, 255), dark=(132, 112, 80, 255), base=(174, 154, 116, 255),
    hi=(204, 186, 146, 255), pale=(230, 218, 186, 255),
    face=(216, 200, 164, 255), ruff=(238, 228, 200, 255),
    nose=(158, 116, 100, 255),
)

# Тёмный горный: предгорья, где зверь темнее и контрастнее.
MOUNTAIN = Coat(
    "manul_mountain",
    deep=(34, 30, 26, 255), dark=(60, 54, 46, 255), base=(92, 84, 72, 255),
    hi=(120, 110, 94, 255), pale=(160, 150, 132, 255),
    face=(136, 126, 108, 255), ruff=(172, 162, 144, 255),
    nose=(114, 84, 78, 255),
)

# Серебристый: редкий, холодный, почти без песочного тепла.
SILVER = Coat(
    "manul_silver",
    deep=(62, 62, 68, 255), dark=(104, 106, 112, 255),
    base=(148, 150, 156, 255), hi=(182, 184, 190, 255),
    pale=(222, 224, 228, 255), face=(202, 204, 210, 255),
    ruff=(234, 236, 240, 255), nose=(150, 122, 126, 255),
)

COATS = (STEPPE, SAND, MOUNTAIN, SILVER)


def save(im, name):
    os.makedirs(OUT, exist_ok=True)
    im.save(os.path.join(OUT, name + ".png"))
    print("entity/" + name)


def cube(im, uv, base, hi, dark):
    """Шесть граней куба по ванильной box-UV раскладке. Свет сверху-слева.

    Раскладка та же, что в gen_quadrupeds/gen_small_fauna: top (u+d, v),
    bottom (u+d+w, v), right (u, v+d), front (u+d, v+d), left (u+d+w, v+d),
    back (u+d+w+d, v+d).
    """
    u, v, w, h, d = uv
    rect(im, u + d, v, u + d + w - 1, v + d - 1, hi)                       # top
    rect(im, u + d + w, v, u + d + w + w - 1, v + d - 1, dark)             # bottom
    rect(im, u, v + d, u + d - 1, v + d + h - 1, dark)                     # right
    rect(im, u + d, v + d, u + d + w - 1, v + d + h - 1, base)             # front
    rect(im, u + d + w, v + d, u + d + w + d - 1, v + d + h - 1, dark)     # left
    rect(im, u + d + w + d, v + d, u + d + w + d + w - 1, v + d + h - 1,
         base)                                                            # back


def fur(im, x0, y0, x1, y1, colour, period=3, offset=0):
    """Подшёрсток: короткие штрихи по решётке, детерминированно.

    Манул мохнатый, и ровная заливка выдаёт «пластиковую» шкуру. Решётка с
    периодом 3-4 даёт зерно, которое видно вблизи и не рябит на дистанции.
    """
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if (x * 2 + y + offset) % period == 0:
                px(im, x, y, colour)


def grumpy_face(im, c):
    """Морда: широкая, плоская, с бровями — главный кадр всей текстуры.

    Передняя грань головы это всего 8×8 px (x 8..15, y 8..15), и именно она
    решает, читается манул как манул.

    Ключевое решение — тёмная «маска» на всю ширину лица (y 9..12), внутри
    которой сидят янтарные глаза. Без неё янтарь тонет: у степного окраса
    яркость лица 168, яркость янтаря 168, то есть глаз не видно вообще ни на
    каком расстоянии. Обводка тёмным тоном собственного цвета (ART_BIBLE §3)
    делает контраст глаза независимым от варианта окраса.

    Опушка идёт двумя столбцами только по нижней половине лица (y 12..15): у
    манула она расходится у челюсти, а не на лбу, и заодно не отнимает пиксели
    у маски, которой нужна вся ширина.
    """
    # Плоскость лица светлее шкуры: у манула лицо бледное, «в маске» наоборот.
    rect(im, 8, 8, 15, 15, c.face)

    # Лоб: тень от надбровий и два тёмных пятна на темени (примета вида).
    hline(im, 8, 8, 15, c.dark)
    px(im, 10, 8, c.deep)
    px(im, 13, 8, c.deep)

    # МАСКА-НАДБРОВЬЕ: тёмный блок на всю ширину лица, y 9..11. Сначала
    # заливаем целиком, потом вырезаем в нём глаза — так каждый пиксель
    # янтаря гарантированно окружён тёмным, включая крайние столбцы.
    # Три ряда, а не четыре: лицо у манула бледное, и если затемнить пол-морды,
    # пропадает именно то, чем он узнаётся.
    rect(im, 8, 9, 15, 11, c.deep)

    # Глаза: янтарные 2×2, широко расставленные, разделённые тёмным столбцом.
    for ex in (10, 13):
        rect(im, ex, 10, ex + 1, 11, AMBER)
        px(im, ex, 10, AMBER_HI)          # блик сверху-слева
        px(im, ex + 1, 11, PUPIL)         # зрачок в нижне-внешнем углу
    px(im, 10, 10, GLINT)                 # один живой блик на всю морду

    # Опушка щёк: столбцы по краям нижней половины — «широкая морда».
    rect(im, 8, 12, 8, 15, c.ruff)
    rect(im, 15, 12, 15, 15, c.ruff)

    # Щёчные полосы: от маски вниз-наружу, двумя тонами для мягкого спада.
    px(im, 9, 12, c.dark)
    px(im, 14, 12, c.dark)
    px(im, 9, 13, c.deep)
    px(im, 14, 13, c.deep)

    # Нос и опущенные углы рта: рот шире носа и уходит вниз по краям.
    rect(im, 11, 13, 12, 13, c.nose)
    hline(im, 14, 11, 12, c.deep)
    px(im, 10, 15, c.deep)
    px(im, 13, 15, c.deep)
    # Подбородок светлый — отделяет морду от груди.
    rect(im, 11, 15, 12, 15, c.pale)


def tail_rings(im, c):
    """Хвост: толстый, с кольцами и тёмным концом.

    Кольца идут через все четыре боковые грани (x 42..53), поэтому опоясывают
    хвост целиком. Толщина 2 px и светлый промежуток между ними обязательны:
    кольцо в 1 px на дистанции пропадает первым, и хвост читается серым
    цилиндром. Ритм задан явно списком, а не циклом с шагом, — чтобы кончик
    хвоста не слипался с последним кольцом в одно тёмное пятно.
    """
    # Светлая подложка на всю длину: контраст кольца строится от неё.
    rect(im, 42, 35, 53, 44, c.pale)
    # Два кольца по 2 px со светлым промежутком в 2 px.
    for y in (36, 40):
        rect(im, 42, y, 53, y + 1, c.deep)
    # Тёмный кончик хвоста — примета манула. Отделён от кольца светлой
    # полосой (y 42..43), иначе низ хвоста сливается в одно пятно.
    rect(im, 42, 44, 53, 44, c.deep)


def manul(c):
    """Собрать текстуру одного окраса."""
    im = Image.new("RGBA", (64, 64), (0, 0, 0, 0))

    # --- Голова ---
    cube(im, UV_HEAD, c.base, c.hi, c.dark)
    grumpy_face(im, c)

    # --- Корпус: 10x16x8 ---
    cube(im, UV_BODY, c.base, c.hi, c.dark)
    # Тёмный хребет по верхней грани — лепит объём на дистанции.
    rect(im, 36, 8, 45, 9, c.dark)
    hline(im, 8, 36, 45, c.deep)
    # Брюхо (нижняя грань) заметно светлее боков.
    rect(im, 46, 8, 55, 15, c.pale)
    # Поперечные размытые полосы на боках: у манула они слабые, но без них
    # корпус читается заливкой. Две полосы по 2 px — минимум, который видно.
    for y in (20, 26):
        rect(im, 36, y, 45, y + 1, c.dark)
        rect(im, 54, y, 63, y + 1, c.dark)
    # Подшёрсток по бокам и спине.
    fur(im, 36, 16, 45, 31, c.hi, period=4)
    fur(im, 54, 16, 63, 31, c.hi, period=4, offset=2)
    fur(im, 28, 16, 35, 31, c.deep, period=5, offset=1)

    # --- Лапа: 4x6x4, с тёмными кольцами ---
    cube(im, UV_LEG, c.base, c.hi, c.dark)
    # Кольца на лапах — та же примета, что на хвосте, и той же толщины 2 px:
    # лапа в игре мелькает в движении, и 1 px на ней не виден вообще.
    rect(im, 0, 20, 15, 21, c.deep)
    # Ступня светлая: отбивает лапу от земли и от тёмного кольца над ней.
    rect(im, 0, 24, 15, 25, c.pale)

    # --- Уши: 3x2x1, маленькие и прижатые ---
    for uv in (UV_EAR_R, UV_EAR_L):
        cube(im, uv, c.ruff, c.pale, c.dark)
    # Тёмная кромка уха: иначе оно теряется на светлой опушке.
    hline(im, 34, 1, 3, c.deep)
    hline(im, 34, 9, 11, c.deep)

    # --- Щёчная опушка: 10x4x2 — то, что делает морду широкой ---
    cube(im, UV_RUFF, c.ruff, c.pale, c.dark)
    # Пряди опушки: вертикальные штрихи по передней грани (x 18..27).
    for x in range(18, 28, 2):
        px(im, x, 36, c.dark)
        px(im, x, 37, c.base)
    # Нижняя кромка опушки темнее — отделяет её от груди.
    hline(im, 37, 18, 27, c.dark)

    # --- Хвост: 3x10x3 ---
    cube(im, UV_TAIL, c.base, c.hi, c.dark)
    tail_rings(im, c)
    return im


def main():
    for coat in COATS:
        save(manul(coat), coat.name)


if __name__ == "__main__":
    main()
